def sourceview(name, T):
    """The text editor's colours (GtkSourceView 4, used by Mousepad): ink page, quiet syntax. Keywords in the accent,
    strings in gold, comments dim and italic, no bold anywhere, a hairline-dim current line. Written into the theme
    pack's home overlay as scheme id "tenka", so switching paths swaps the file and the editor's setting stays put."""
    p = T["p"]
    def mix(c1, c2, a):
        c1, c2 = c1.lstrip("#"), c2.lstrip("#")
        return "#" + "".join(f"{round(int(c1[i:i+2], 16) * (1 - a) + int(c2[i:i+2], 16) * a):02x}" for i in (0, 2, 4))
    dim = mix(p["text"], p["base"], 0.5)
    styles = [
        ("text", f'foreground="{p["text"]}" background="{p["base"]}"'),
        ("selection", f'foreground="{p["text"]}" background="{mix(p["base"], p["accent"], 0.32)}"'),
        ("selection-unfocused", f'background="{mix(p["base"], p["accent"], 0.18)}"'),
        ("cursor", f'foreground="{p["accent2"]}"'),
        ("current-line", f'background="{mix(p["base"], p["text"], 0.045)}"'),
        ("current-line-number", f'foreground="{p["accent2"]}" background="{p["mantle"]}"'),
        ("line-numbers", f'foreground="{mix(p["text"], p["base"], 0.62)}" background="{p["mantle"]}"'),
        ("right-margin", f'foreground="{p["accent2"]}" background="{p["mantle"]}"'),
        ("bracket-match", f'foreground="{p["text"]}" background="{mix(p["base"], p["accent2"], 0.28)}"'),
        ("bracket-mismatch", f'foreground="{p["text"]}" background="{mix(p["base"], p["accent"], 0.45)}"'),
        ("search-match", f'foreground="{p["text"]}" background="{mix(p["base"], p["accent2"], 0.35)}"'),
        ("draw-spaces", f'foreground="{mix(p["text"], p["base"], 0.8)}"'),
        ("def:comment", f'foreground="{dim}" italic="true"'),
        ("def:shebang", f'foreground="{dim}" italic="true"'),
        ("def:doc-comment-element", f'foreground="{dim}"'),
        ("def:keyword", f'foreground="{p["accent_l"]}"'),
        ("def:statement", f'foreground="{p["accent_l"]}"'),
        ("def:type", f'foreground="{p["alt"]}"'),
        ("def:builtin", f'foreground="{p["alt"]}"'),
        ("def:function", f'foreground="{p["text"]}"'),
        ("def:identifier", f'foreground="{p["text"]}"'),
        ("def:string", f'foreground="{p["accent2"]}"'),
        ("def:special-char", f'foreground="{p["soft"]}"'),
        ("def:constant", f'foreground="{p["soft"]}"'),
        ("def:number", f'foreground="{p["soft"]}"'),
        ("def:boolean", f'foreground="{p["soft"]}"'),
        ("def:preprocessor", f'foreground="{p["subtext"]}"'),
        ("def:note", f'foreground="{p["accent2"]}" background="{p["base"]}"'),
        ("def:error", f'underline="error" underline-color="{p["accent"]}"'),
        ("def:warning", f'underline="error" underline-color="{p["accent2"]}"'),
        ("def:heading", f'foreground="{p["accent2"]}"'),
        ("def:emphasis", 'italic="true"'),
        ("def:strong-emphasis", f'foreground="{p["text"]}"'),
        ("def:link-text", f'foreground="{p["alt"]}"'),
        ("def:net-address", f'foreground="{p["alt"]}" underline="single"'),
        ("diff:added-line", f'foreground="{p["green"]}"'),
        ("diff:removed-line", f'foreground="{p["accent"]}"'),
        ("diff:location", f'foreground="{p["accent2"]}"'),
    ]
    body = "\n".join(f'  <style name="{n}" {a}/>' for n, a in styles)
    W(os.path.join(ROOT, f"themes/{name}/home/.local/share/gtksourceview-4/styles/tenka.xml"),
      f'<?xml version="1.0" encoding="UTF-8"?>\n<!-- generated by scripts/gen-lite.py: the text editor in {T["display"]} -->\n'
      f'<style-scheme id="tenka" name="{T["display"]}" version="1.0">\n  <author>Tenka</author>\n'
      f'  <description>Ink page, quiet syntax, no bold.</description>\n{body}\n</style-scheme>\n')

