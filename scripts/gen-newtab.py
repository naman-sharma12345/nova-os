#!/usr/bin/env python3
# Writes live/config/includes.chroot/usr/share/tenka/newtab/<theme>.js: the words, colours and art The Courtyard
# (Firefox's new tab and home page, usr/share/tenka/newtab/index.html) needs, from the pack's own
# themes/<theme>/home/.config/tenka/shell-theme.json (gen-shell.py), so the page says what the desk says:
# the same seek word, the same proverb of the day, the same seal. Run by assemble.sh; output is committed.
import json, os, sys, importlib.machinery, importlib.util
sys.dont_write_bytecode = True   # no __pycache__ beside tenka-almanac in usr/bin
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# The Almanac's words come from tenka-almanac itself (one list: the desk, the terminal and this page agree)
_p = os.path.join(ROOT, "live/config/includes.chroot/usr/bin/tenka-almanac")
_l = importlib.machinery.SourceFileLoader("tenka_almanac", _p)
ALM = importlib.util.module_from_spec(importlib.util.spec_from_loader("tenka_almanac", _l)); _l.exec_module(ALM)
OUT = os.path.join(ROOT, "live/config/includes.chroot/usr/share/tenka/newtab")
KEYS = ["name", "display", "tagline", "base", "surface", "accent", "gold", "text", "subtext", "seekWord", "crest", "proverbs"]
os.makedirs(OUT, exist_ok=True)
for name in sorted(os.listdir(os.path.join(ROOT, "themes"))):
    src = os.path.join(ROOT, "themes", name, "home/.config/tenka/shell-theme.json")
    if not os.path.isfile(src):
        continue
    t = json.load(open(src))
    d = {k: t[k] for k in KEYS if k in t}
    d["wall"] = t["wallpaper"].replace("/wallpapers/", "/wallpapers-blur/")
    d["page"] = "The Pavilion" if name == "xianxia" else "The Courtyard"
    # terms from the Spring Equinox; details: Tianxia one saying per term, Tenka the 72 micro-seasons
    d["almanac"] = {"terms": ALM.TERMS, "details": ALM.SAYINGS if name == "xianxia" else ALM.KO}
    with open(os.path.join(OUT, name + ".js"), "w") as f:
        f.write("// generated by scripts/gen-newtab.py from themes/%s/home/.config/tenka/shell-theme.json\n" % name)
        f.write("window.TENKA = " + json.dumps(d, ensure_ascii=False, indent=1) + ";\n")
    print("newtab:", name)
