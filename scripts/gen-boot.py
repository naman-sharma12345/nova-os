#!/usr/bin/env python3
"""Tenka boot menu (GRUB): a title-card screen per theme.

The key art is graded, the wordmark is baked in as art (glow, ink bleed, gold hairline,
tracked tagline), and the menu floats in Marcellus over a soft ink falloff. The selected
entry gets a vermilion dry-brush stroke (Tenka) or a jade glow with a gold bead (Tianxia).
Writes a 1080p theme (theme.txt) and a 4K one (theme-4k.txt) per pack, plus the live ISO menu.

    python3 scripts/gen-boot.py
"""
import os, shutil, subprocess, textwrap, importlib.util
import numpy as np
from PIL import Image, ImageDraw, ImageFilter
HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("tenka_art", os.path.join(HERE, "tenka_art.py"))
ta = importlib.util.module_from_spec(spec); spec.loader.exec_module(ta)
ROOT = ta.ROOT
IC = os.path.join(ROOT, "live/config/includes.chroot")
MENU = dict(left=116, top=540, width=520, ih=62, sp=10, text_inset=36, font=34)
ENTRIES = ("Tenka", "Tianxia", "Tenka Lite", "Safe graphics")
BAR_Y = 984  # the countdown line sits just above the key hints (fits 1024x768 too)


def pct(v, total):
    return f"{100 * v / total:.2f}%"


BLANK = ("nw", "n", "ne", "w", "e", "sw", "s", "se")


def background(theme, s=1):
    c = ta.scene(theme, s)
    c, _ = ta.title_block(c, theme, s)
    P = ta.PAL[theme]
    ta.place_text(c, (ta.LX * s, int(1012 * s)), "ENTER  to begin      E  to edit      C  for console",
                  ta.MARC, int(15 * s), ta.hexc(P["text"], 120), track_em=0.18)
    return c.convert("RGB")


def sel_samurai(w, h, s=1):
    a = ta.brush_stroke(int(w * 0.80), int(h * 0.92), seed=23, dry=0.45, head=0.03, tail=0.6, wave=0.04)
    m = ta.mask_img(a).rotate(1.2, resample=Image.BICUBIC)
    M = Image.new("L", (w, h), 0); M.paste(m, (int(2 * s), int(h * 0.04)))
    lay = Image.new("RGBA", (w, h), ta.hexc("#d8412f")[:3] + (0,)); lay.putalpha(M.point(lambda v: int(v * 0.9)))
    core = Image.new("RGBA", (w, h), (140, 26, 20, 0))
    core.putalpha(M.filter(ImageFilter.GaussianBlur(1.5 * s)).point(lambda v: int(max(0, v - 170) * 0.6)))
    return Image.alpha_composite(lay, core)


def sel_xianxia(w, h, s=1):
    """Flat and crisp (Naman: no neon, no glow): a pale jade band with hard edges that fades to the right,
    a 2px jade rule along its foot and a short jade tick at the left. No blur, no bloom, no bead."""
    xx = np.linspace(0, 1, w)[None, :].repeat(h, 0)
    fade = np.clip(1 - xx / 0.82, 0, 1) ** 1.1
    arr = np.zeros((h, w, 4), np.float32); arr[..., :3] = ta.hexc("#5fc9a0")[:3]
    top, bot = int(h * 0.10), int(h * 0.88)
    band = np.zeros((h, w), np.float32); band[top:bot] = 0.20
    rule = np.zeros((h, w), np.float32); t = max(2, int(2 * s)); rule[bot - t:bot] = 0.95
    tick = np.zeros((h, w), np.float32); tick[top:bot, :max(3, int(3 * s))] = 1.0
    arr[..., 3] = np.clip(np.maximum(np.maximum(band, rule) * fade, tick), 0, 1) * 255
    return Image.fromarray(arr.astype(np.uint8), "RGBA")


def countdown(theme, w, h, s=1):
    P = ta.PAL[theme]
    tr = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    ImageDraw.Draw(tr).line((0, h // 2, w, h // 2), fill=ta.hexc(P["gold"], 70), width=max(1, int(s)))
    hl = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    ImageDraw.Draw(hl).line((0, h // 2, w, h // 2), fill=ta.hexc(P["acc"], 230), width=max(2, int(2 * s)))
    return tr, hl   # crisp, no glow


def fonts(d):
    if not shutil.which("grub-mkfont"): return
    for sz in (16, 32, MENU["font"], MENU["font"] * 2):
        subprocess.run(["grub-mkfont", "-r", "0x20-0x7E,0xA0-0xFF,0x2013-0x2022", "-s", str(sz), "-n", "Marcellus", "-o", os.path.join(d, f"marcellus-{sz}.pf2"), ta.MARC], check=False)


def theme_txt(theme, s, bgname, suffix):
    P = ta.PAL[theme]; M = {k: (int(v * s) if isinstance(v, int) else v) for k, v in MENU.items()}
    n = len(ENTRIES)
    return textwrap.dedent(f"""\
    # {P['display']} boot menu ({'4K' if s == 2 else '1080p'}), generated by scripts/gen-boot.py
    title-text: ""
    desktop-image: "{bgname}"
    desktop-image-scale-method: "stretch"
    desktop-color: "{P['base']}"
    terminal-font: "Marcellus Regular {16 * s}"
    terminal-left: "8%"
    terminal-top: "8%"
    terminal-width: "84%"
    terminal-height: "84%"
    terminal-border: "0"

    + boot_menu {{
        left = {M['left']}
        top = 50%{'+' if M['top'] >= 540 * s else '-'}{abs(M['top'] - 540 * s)}
        width = {M['width']}
        height = {n * M['ih'] + (n - 1) * M['sp'] + int(20 * s)}
        item_font = "Marcellus Regular {MENU['font'] * s}"
        selected_item_font = "Marcellus Regular {MENU['font'] * s}"
        item_color = "{P['unsel']}"
        selected_item_color = "{P['sel']}"
        item_height = {M['ih']}
        item_padding = 0
        item_spacing = {M['sp']}
        icon_width = 0
        icon_height = 0
        item_icon_space = {M['text_inset']}
        selected_item_pixmap_style = "select{suffix}_*.png"
        scrollbar = false
    }}

    + progress_bar {{
        id = "__timeout__"
        left = {ta.LX * s}
        top = 100%-{(1080 - BAR_Y) * s}
        width = {360 * s}
        height = {14 * s}
        bar_style = "bar{suffix}_*.png"
        highlight_style = "hl{suffix}_*.png"
        text = ""
    }}
    """)


def build_theme(theme, d):
    shutil.rmtree(d, ignore_errors=True); os.makedirs(d, exist_ok=True)
    for s, suffix, bgname, tname in ((1, "", "background.png", "theme.txt"), (2, "-4k", "background-4k.png", "theme-4k.txt")):
        background(theme, s).save(os.path.join(d, bgname))
        w, h = MENU["width"] * s, MENU["ih"] * s
        (sel_samurai if theme == "samurai" else sel_xianxia)(w, h, s).save(os.path.join(d, f"select{suffix}_c.png"))
        tr, hl = countdown(theme, 360 * s, 14 * s, s)
        tr.save(os.path.join(d, f"bar{suffix}_c.png")); hl.save(os.path.join(d, f"hl{suffix}_c.png"))
        for nm in ("select", "bar", "hl"):
            for k in BLANK: Image.new("RGBA", (1, 1), (0, 0, 0, 0)).save(os.path.join(d, f"{nm}{suffix}_{k}.png"))
        with open(os.path.join(d, tname), "w") as f: f.write(theme_txt(theme, s, bgname, suffix))
    fonts(d)


def sddm_assets(theme, d):
    """The login's 'title' face reuses the boot menu's own art: the graded key art + baked wordmark
    (no key hints: the greeter draws its own) and the selected-entry stroke, so GRUB hands over to
    the login without a seam."""
    c = ta.scene(theme, 1)
    c, _ = ta.title_block(c, theme, 1)
    c.convert("RGB").save(os.path.join(d, "title.jpg"), quality=92)
    (sel_samurai if theme == "samurai" else sel_xianxia)(MENU["width"], MENU["ih"], 1).save(os.path.join(d, "select.png"))


LIVE_CFG = """source /boot/grub/config.cfg

menuentry "Tenka" --class tenka --hotkey=t {
    linux @KERNEL_LIVE@ @APPEND_LIVE@ tenka.theme=samurai
    initrd @INITRD_LIVE@
}
menuentry "Tianxia" --class tianxia --hotkey=x {
    linux @KERNEL_LIVE@ @APPEND_LIVE@ tenka.theme=xianxia plymouth.splash=tenka-xianxia
    initrd @INITRD_LIVE@
}
menuentry "Tenka Lite" --class lite --hotkey=l {
    linux @KERNEL_LIVE@ @APPEND_LIVE@ tenka.session=lite
    initrd @INITRD_LIVE@
}
menuentry "Safe graphics" --class safe --hotkey=s {
    linux @KERNEL_LIVE@ @APPEND_LIVE@ nomodeset tenka.session=lite
    initrd @INITRD_LIVE@
}
"""


def live():
    lb = os.path.join(ROOT, "live/config/bootloaders/grub-pc")
    if not os.path.exists(os.path.join(lb, "install_start_gui.cfg")):
        shutil.copytree("/usr/share/live/build/bootloaders/grub-pc", lb, dirs_exist_ok=True)
    build_theme("samurai", os.path.join(lb, "live-theme"))
    shutil.copy(os.path.join(lb, "live-theme/background.png"), os.path.join(ROOT, "live/config/bootloaders/splash.png"))
    with open(os.path.join(lb, "theme.cfg"), "w") as f:
        f.write("set color_normal=light-gray/black\nset color_highlight=white/black\n"
                f"loadfont /boot/grub/live-theme/marcellus-16.pf2\nloadfont /boot/grub/live-theme/marcellus-{MENU['font']}.pf2\n"
                "set theme=/boot/grub/live-theme/theme.txt\n")
    with open(os.path.join(lb, "config.cfg"), "w") as f:
        f.write(textwrap.dedent("""\
        set default=0
        set timeout=8
        set timeout_style=menu
        insmod all_video
        insmod gfxterm
        insmod png
        set gfxmode=1920x1080,auto
        set gfxpayload=keep
        loadfont /boot/grub/live-theme/marcellus-16.pf2
        terminal_output gfxterm
        source /boot/grub/theme.cfg
        """))
    with open(os.path.join(lb, "grub.cfg"), "w") as f: f.write(LIVE_CFG)


if __name__ == "__main__":
    for n in ta.PAL:
        build_theme(n, os.path.join(IC, f"usr/share/grub/themes/tenka-{n}")); print("grub theme:", n)
        sd = os.path.join(IC, f"usr/share/sddm/themes/tenka-{n}"); os.makedirs(sd, exist_ok=True)
        sddm_assets(n, sd); print("sddm title art:", n)
    live(); print("live boot menu: samurai")
