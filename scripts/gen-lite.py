#!/usr/bin/env python3
"""Tenka Lite theme generator: GTK theme (Orchis-Dark base + Tenka overrides), xfwm4 window
decorations drawn per theme, xfce4-notifyd theme and xfce4-terminal colours.

    python3 scripts/gen-lite.py
"""
import os, textwrap, importlib.util
from PIL import Image, ImageDraw, ImageFilter
HERE = os.path.dirname(os.path.abspath(__file__))
spec = importlib.util.spec_from_file_location("gt", os.path.join(HERE, "gen-themes.py"))
gt = importlib.util.module_from_spec(spec); spec.loader.exec_module(gt)
ROOT = gt.ROOT
IC = os.path.join(ROOT, "live/config/includes.chroot")

def rgb(c, a=255): c = c.lstrip("#"); return (int(c[0:2], 16), int(c[2:4], 16), int(c[4:6], 16), a)
def W(path, s):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write(s)

TITLE_H = 34
SS = 4  # supersampling

def xfwm4(name, T, d):
    p = T["p"]; os.makedirs(d, exist_ok=True)
    R = 12 if name == "xianxia" else 9
    for state in ("active", "inactive"):
        act = state == "active"
        top = rgb(p["surface"]) if act else rgb(p["base"])
        line = rgb(p["accent2"], 120 if act else 40)
        edge = rgb(p["overlay"], 255)
        # title strip pieces (1..5 are all the same tile)
        tile = Image.new("RGBA", (8, TITLE_H), top)
        dd = ImageDraw.Draw(tile)
        dd.line((0, 0, 8, 0), fill=rgb(p["text"], 22 if act else 10))  # top highlight
        dd.line((0, TITLE_H - 1, 8, TITLE_H - 1), fill=line)
        for i in range(1, 6): tile.save(os.path.join(d, f"title-{i}-{state}.png"))
        # rounded top corners, drawn at 4x then downsampled
        for side in ("left", "right"):
            big = Image.new("RGBA", (R * SS, TITLE_H * SS), (0, 0, 0, 0)); bd = ImageDraw.Draw(big)
            x0 = 0 if side == "left" else -R * SS
            bd.rounded_rectangle((x0, 0, x0 + 2 * R * SS, TITLE_H * SS * 2), radius=R * SS, fill=top, outline=edge, width=SS)
            im = big.resize((R, TITLE_H), Image.LANCZOS)
            ImageDraw.Draw(im).line((0, TITLE_H - 1, R, TITLE_H - 1), fill=line)
            im.save(os.path.join(d, f"top-{side}-{state}.png"))
        # sides + bottom (thin)
        for nm, size in (("left", (2, 8)), ("right", (2, 8)), ("bottom", (8, 2)), ("bottom-left", (2, 2)), ("bottom-right", (2, 2))):
            Image.new("RGBA", size, edge if act else rgb(p["mantle"])).save(os.path.join(d, f"{nm}-{state}.png"))
    # buttons: themed beads. samurai = ink dots (vermilion close), xianxia = jade beads with a gold rim
    colours = {"close": p["accent"], "maximize": p["accent2"], "hide": p["alt"] if name == "samurai" else p["accent_l"]}
    for b, col in colours.items():
        for st in ("active", "inactive", "prelight", "pressed"):
            big = Image.new("RGBA", (24 * SS, TITLE_H * SS), (0, 0, 0, 0)); bd = ImageDraw.Draw(big)
            cx, cy, r = 12 * SS, TITLE_H * SS // 2, 6 * SS
            c = rgb(col) if st != "inactive" else rgb(p["overlay"])
            if st == "prelight":
                glow = Image.new("RGBA", big.size, (0, 0, 0, 0)); gd = ImageDraw.Draw(glow)
                gd.ellipse((cx - r * 2, cy - r * 2, cx + r * 2, cy + r * 2), fill=rgb(col, 110))
                big = Image.alpha_composite(big, glow.filter(ImageFilter.GaussianBlur(4 * SS))); bd = ImageDraw.Draw(big)
            rr = r + (SS if st == "prelight" else 0) - (SS if st == "pressed" else 0)
            bd.ellipse((cx - rr, cy - rr, cx + rr, cy + rr), fill=c)
            if name == "xianxia" and st != "inactive":
                bd.ellipse((cx - rr, cy - rr, cx + rr, cy + rr), outline=rgb(p["accent2"], 200), width=SS)
                bd.ellipse((cx - rr // 3 - SS, cy - rr // 2 - SS, cx - rr // 3 + SS * 2, cy - rr // 2 + SS * 2), fill=(255, 255, 255, 120))
            im = big.resize((24, TITLE_H), Image.LANCZOS)
            im.save(os.path.join(d, f"{b}-{st}.png"))
            if b == "maximize": im.save(os.path.join(d, f"maximize-toggled-{st}.png"))
    for b in ("menu", "shade", "stick"):
        for st in ("active", "inactive", "prelight", "pressed"):
            Image.new("RGBA", (2, TITLE_H), (0, 0, 0, 0)).save(os.path.join(d, f"{b}-{st}.png"))
            Image.new("RGBA", (2, TITLE_H), (0, 0, 0, 0)).save(os.path.join(d, f"{b}-toggled-{st}.png"))
    W(os.path.join(d, "themerc"), textwrap.dedent(f"""\
    # {T['display']} xfwm4 decorations (generated by scripts/gen-lite.py)
    active_text_color={p['text']}
    inactive_text_color={p['subtext']}
    title_horizontal_offset=0
    title_vertical_offset_active=1
    title_vertical_offset_inactive=1
    title_shadow_active=false
    title_shadow_inactive=false
    full_width_title=true
    title_alignment=center
    button_offset=8
    button_spacing=0
    show_app_icon=false
    maximized_offset=0
    """))

def gtk_theme(name, T, d):
    p = T["p"]; r = T["rounding"]; disp = T["font_display"]
    A = lambda c, a: gt.rgba(c, a)
    css = textwrap.dedent(f"""\
    /* {T['display']} GTK3 theme: Orchis-Dark structure, Tenka colours (generated by scripts/gen-lite.py) */
    @import url("../../Orchis-Dark/gtk-3.0/gtk.css");
    @define-color theme_bg_color {p['base']};
    @define-color theme_base_color {p['mantle']};
    @define-color theme_fg_color {p['text']};
    @define-color theme_text_color {p['text']};
    @define-color theme_selected_bg_color {p['accent']};
    @define-color theme_selected_fg_color {p['text']};
    @define-color accent_color {p['accent']};

    window.background, .background {{ background-color: {p['base']}; color: {p['text']}; }}
    .view, iconview, treeview.view, textview text {{ background-color: {p['mantle']}; color: {p['text']}; }}
    headerbar, .titlebar, menubar, toolbar {{ background-color: {p['surface']}; color: {p['text']}; box-shadow: none; }}
    .sidebar, placessidebar, placessidebar list {{ background-color: {p['base']}; }}
    *:selected, selection, row:selected, .view:selected {{ background-color: {A(p['accent'], 0.85)}; color: {p['text']}; }}
    entry {{ background-color: {p['mantle']}; color: {p['text']}; border-color: {A(p['subtext'], 0.3)}; border-radius: {max(6, r - 4)}px; }}
    entry:focus {{ border-color: {p['accent']}; box-shadow: inset 0 0 0 1px {p['accent']}; }}
    button.suggested-action {{ background-color: {p['accent']}; color: {p['text']}; }}
    scale highlight, progressbar progress, switch:checked {{ background-color: {p['accent']}; }}
    check:checked, radio:checked {{ background-color: {p['accent']}; color: {p['text']}; }}
    menu, .menu, .context-menu, popover, popover.background {{ background-color: {p['surface']}; color: {p['text']}; border: 1px solid {A(p['accent2'], 0.25)}; border-radius: {r}px; }}
    menuitem:hover, menu menuitem:hover {{ background-color: {A(p['accent'], 0.30)}; }}
    tooltip, tooltip.background {{ background-color: {A(p['base'], 0.95)}; color: {p['text']}; border: 1px solid {A(p['accent2'], 0.35)}; border-radius: {r}px; }}
    link, *:link {{ color: {p['accent2']}; }}

    /* ---- Tenka Lite panels, mirroring the Tenka shell: the top bar is bare (its colour comes from
       the panel's own transparent background); the dock's glass is its background-rgba, rounded here ---- */
    .xfce4-panel.background {{
        background-image: none; background-color: transparent; border-radius: 22px; border: none;
        color: {p['text']};
    }}
    .xfce4-panel button {{ color: {p['text']}; border-radius: {r}px; padding: 2px 8px; background: transparent; border: none; box-shadow: none; }}
    .xfce4-panel button:hover {{ background-color: {A(p['text'], 0.08)}; }}
    .xfce4-panel button:checked, .xfce4-panel button:active {{ background-color: {A(p['accent'], 0.22)}; color: {p['accent2']}; }}
    .xfce4-panel label {{ font-family: Marcellus; font-size: 13px; letter-spacing: 1px; }}
    #genmon-11 {{ padding: 0 6px; }}
    #whiskermenu-button {{ padding: 0 10px; }}
    #whiskermenu-button label {{ font-family: "{disp}"; font-size: 15px; color: {p['text']}; }}
    #genmon-tenka label, .genmon_value {{ font-family: "{disp}"; font-size: 15px; color: {p['text']}; }}
    #clock-button label {{ font-family: "{disp}"; font-size: 15px; }}

    /* plugin frames: no boxes, just text and light */
    .xfce4-panel frame > border, .xfce4-panel frame {{ border: none; box-shadow: none; background: transparent; }}

    /* docklike: active window gets the theme's mark */
    .docklike-plugin button {{ border-radius: {r}px; }}
    .docklike-plugin button.active_group {{ background: linear-gradient(0deg, {A(p['accent'], 0.30)}, transparent 60%); }}

    /* ---- Whisker menu ---- */
    #whiskermenu-window {{ background-color: {A(p['base'], 0.97)}; border: 1px solid {A(p['accent2'], 0.35)}; border-radius: {r + 8}px; }}
    #whiskermenu-window entry {{ background-color: {p['mantle']}; border-radius: {r}px; padding: 8px 12px; }}
    #whiskermenu-window treeview, #whiskermenu-window iconview, #whiskermenu-window scrolledwindow, #whiskermenu-window viewport {{ background-color: transparent; }}
    #whiskermenu-window button {{ border-radius: {r}px; }}
    #whiskermenu-window button:checked, #whiskermenu-window .view:selected {{ background-color: {A(p['accent'], 0.30)}; color: {p['text']}; }}
    #whiskermenu-window label {{ color: {p['text']}; }}

    /* ---- desktop icons ---- */
    XfdesktopIconView.view {{ background: transparent; color: {p['text']}; text-shadow: 0 1px 3px rgba(0,0,0,0.8); }}
    """)
    W(os.path.join(d, "gtk-3.0/gtk.css"), css)
    W(os.path.join(d, "gtk-3.0/gtk-dark.css"), css)
    W(os.path.join(d, "index.theme"), textwrap.dedent(f"""\
    [Desktop Entry]
    Type=X-GNOME-Metatheme
    Name=Tenka-{name.capitalize()}
    Comment={T['display']}: {T['tagline']}
    Encoding=UTF-8

    [X-GNOME-Metatheme]
    GtkTheme=Tenka-{name.capitalize()}
    MetacityTheme=Tenka-{name.capitalize()}
    IconTheme={T['icons']}
    CursorTheme={T['cursor']}
    ButtonLayout=:minimize,maximize,close
    """))
    # notifications (xfce4-notifyd theme lives inside the GTK theme dir)
    W(os.path.join(d, "xfce-notify-4.0/gtk.css"), textwrap.dedent(f"""\
    #XfceNotifyWindow {{ background-color: {A(p['base'], 0.94)}; border: 1px solid {A(p['accent2'], 0.45)}; border-radius: {r + 4}px; }}
    #XfceNotifyWindow:hover {{ border-color: {p['accent']}; }}
    #XfceNotifyWindow label#summary {{ font-family: "{disp}"; font-size: 15px; color: {p['accent2']}; }}
    #XfceNotifyWindow label#body {{ font-family: Inter; color: {p['text']}; }}
    #XfceNotifyWindow progressbar progress {{ background-color: {p['accent']}; }}
    #XfceNotifyWindow button {{ background-color: {p['surface']}; color: {p['text']}; border-radius: {r}px; }}
    """))

def terminal(name, T):
    p = T["p"]; k = {}
    for line in open(os.path.join(ROOT, f"themes/{name}/home/.config/kitty/theme.conf")):
        bits = line.split()
        if len(bits) == 2 and bits[0].startswith("color"): k[int(bits[0][5:])] = bits[1]
    W(os.path.join(ROOT, f"themes/{name}/home/.config/xfce4/terminal/terminalrc"), textwrap.dedent(f"""\
    [Configuration]
    FontName=JetBrains Mono 11
    ColorForeground={p['text']}
    ColorBackground={p['base']}
    ColorCursor={p['accent']}
    ColorSelection={p['overlay']}
    ColorBold={p['text']}
    ColorBoldUseDefault=FALSE
    ColorPalette={';'.join(k[i] for i in range(16))}
    BackgroundMode=TERMINAL_BACKGROUND_TRANSPARENT
    BackgroundDarkness=0.88
    MiscBorderless=FALSE
    MiscMenubarDefault=FALSE
    MiscToolbarDefault=FALSE
    ScrollingBar=TERMINAL_SCROLLBAR_NONE
    MiscCursorShape=TERMINAL_CURSOR_SHAPE_IBEAM
    MiscDefaultGeometry=110x30
    TitleMode=TERMINAL_TITLE_HIDE
    """))

def lock_art(name):
    """The Lite lock screen and the panel's title-card wallpaper: the key art with the baked title."""
    sp = importlib.util.spec_from_file_location("tenka_art", os.path.join(HERE, "tenka_art.py"))
    ta = importlib.util.module_from_spec(sp); sp.loader.exec_module(ta)
    c = ta.scene(name); c, _ = ta.title_block(c, name)
    d = os.path.join(ROOT, "themes", name, "lock"); os.makedirs(d, exist_ok=True)
    c.convert("RGB").save(os.path.join(d, "lock.jpg"), quality=92)


if __name__ == "__main__":
    for n, T in gt.THEMES.items():
        lock_art(n)
        d = os.path.join(IC, f"usr/share/themes/Tenka-{n.capitalize()}")
        gtk_theme(n, T, d); xfwm4(n, T, os.path.join(d, "xfwm4")); terminal(n, T)
        print("lite theme:", n)
